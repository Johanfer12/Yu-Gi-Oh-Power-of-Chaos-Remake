# Retail CD and the legacy local EXE differ at this one dispatch identity.
RETAIL_FUNCTIONS = dict(FUNCTIONS)
RETAIL_FUNCTIONS.pop(0x53de80)
RETAIL_FUNCTIONS[0x53de90] = 0x53b790


def build(pe):
    # The dispatch identity tells the layouts apart: the local and US retail EXEs point
    # at 0x53de80, the Spanish retail CD at 0x53de90 (an MD5 would miss the US disc).
    tables = pe.read(0x5ad6f0, 0x2d00)
    pointers = {struct.unpack_from('<I', tables, offset)[0] for offset in range(0, len(tables), 4)}
    functions = FUNCTIONS if 0x53de80 in pointers else RETAIL_FUNCTIONS
    output = bytearray(0x15000)
    # Kaiba engine constants; these virtual-address ranges are validated by its profile.
    for target, source, size in ((0x59a5b8, 0x59d5ec, 20),
                                  (0x59df1c, 0x5a0ffc, 0x61c),
                                  (0x5aa6e8, 0x5ad6f0, 0x2d00)):
        data = bytearray(pe.read(source, size))
        if target == 0x5aa6e8:
            for offset in range(0, len(data), 4):
                pointer = struct.unpack_from('<I', data, offset)[0]
                if 0x5a0ffc <= pointer < 0x5a1618:
                    struct.pack_into('<I', data, offset, pointer - 0x30e0)
                elif pointer in functions:
                    struct.pack_into('<I', data, offset, functions[pointer])
        output[target - 0x59a000:target - 0x59a000 + size] = data
    return bytes(output)
